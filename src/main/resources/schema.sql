CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(40) NOT NULL UNIQUE,
    display_name VARCHAR(60) NOT NULL,
    password_hash VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    owner_id BIGINT NOT NULL REFERENCES users(id),
    created_at VARCHAR(40) NOT NULL
);
CREATE TABLE IF NOT EXISTS project_members (
    project_id BIGINT NOT NULL REFERENCES projects(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    role VARCHAR(10) NOT NULL CHECK (role IN ('owner', 'editor', 'viewer')),
    PRIMARY KEY(project_id, user_id)
);
CREATE TABLE IF NOT EXISTS tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL,
    description VARCHAR(2000) NOT NULL DEFAULT '',
    assignee VARCHAR(60) NOT NULL DEFAULT '',
    priority VARCHAR(10) NOT NULL CHECK (priority IN ('low', 'medium', 'high')),
    status VARCHAR(10) NOT NULL CHECK (status IN ('backlog', 'doing', 'blocked', 'done')),
    version BIGINT NOT NULL DEFAULT 0,
    due_date DATE,
    created_at VARCHAR(40) NOT NULL,
    updated_at VARCHAR(40) NOT NULL
);
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS project_id BIGINT REFERENCES projects(id);
CREATE INDEX IF NOT EXISTS idx_tasks_project ON tasks(project_id, status, updated_at);
CREATE INDEX IF NOT EXISTS idx_tasks_status_priority ON tasks(status, priority);
CREATE INDEX IF NOT EXISTS idx_tasks_due_date ON tasks(due_date);
CREATE TABLE IF NOT EXISTS activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES tasks(id),
    action VARCHAR(30) NOT NULL,
    detail VARCHAR(300) NOT NULL,
    created_at VARCHAR(40) NOT NULL
);
ALTER TABLE activities ADD COLUMN IF NOT EXISTS actor VARCHAR(40) NOT NULL DEFAULT 'legacy_demo';
CREATE INDEX IF NOT EXISTS idx_activities_task ON activities(task_id, id);
CREATE TABLE IF NOT EXISTS comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES tasks(id),
    actor VARCHAR(40) NOT NULL,
    body VARCHAR(1000) NOT NULL,
    created_at VARCHAR(40) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_comments_task ON comments(task_id, id);
CREATE TABLE IF NOT EXISTS project_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id),
    task_id BIGINT,
    actor VARCHAR(40) NOT NULL,
    action VARCHAR(30) NOT NULL,
    detail VARCHAR(300) NOT NULL,
    created_at VARCHAR(40) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_project_activities ON project_activities(project_id, id);
